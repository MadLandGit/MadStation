#!/usr/bin/env node
/**
 * Refresh the bundled Public Suffix List from Mozilla's authoritative URL.
 * Run with: npm run update:psl
 * This maintainer script intentionally rejects redirects and non-official hosts.
 */
import { writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { domainToASCII } from 'node:url';

export const OFFICIAL_PSL_URL = 'https://publicsuffix.org/list/public_suffix_list.dat';
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

function normalizedRule(input) {
  let rule = String(input || '').trim().toLowerCase();
  let prefix = '';
  if (rule.startsWith('!')) { prefix = '!'; rule = rule.slice(1); }
  else if (rule.startsWith('*.')) { prefix = '*.'; rule = rule.slice(2); }
  if (!rule || /[\s/\`{}$]/.test(rule)) throw new Error(`Invalid PSL rule: ${input}`);
  const ascii = domainToASCII(rule);
  if (!ascii || !/^[a-z0-9.-]+$/.test(ascii) || ascii.startsWith('.') || ascii.endsWith('.') || ascii.includes('..')) {
    throw new Error(`Invalid PSL hostname rule: ${input}`);
  }
  return prefix + ascii.toLowerCase();
}

export function parseOfficialPsl(text, { minRules = 9000 } = {}) {
  if (typeof text !== 'string' || text.length < 100_000) throw new Error('PSL response is unexpectedly short');
  const version = text.match(/^\/\/ VERSION: (\S+)\s*$/m)?.[1];
  const commit = text.match(/^\/\/ COMMIT: ([a-f0-9]{40})\s*$/m)?.[1];
  if (!version || !commit) throw new Error('PSL VERSION or COMMIT header is missing');
  const lines = text.split(/\r?\n/);
  const rules = new Set();
  let inPslSection = false;
  let sawIcan = false;
  let sawPrivate = false;
  for (const rawLine of lines) {
    const line = rawLine.trim();
    if (/^\/\/ ===BEGIN ICANN DOMAINS===/.test(line)) { inPslSection = true; sawIcan = true; continue; }
    if (/^\/\/ ===BEGIN PRIVATE DOMAINS===/.test(line)) { inPslSection = true; sawPrivate = true; continue; }
    if (/^\/\/ ===END (ICANN|PRIVATE) DOMAINS===/.test(line)) { inPslSection = false; continue; }
    if (!inPslSection || !line || line.startsWith('//')) continue;
    rules.add(normalizedRule(line));
  }
  if (!sawIcan || !sawPrivate) throw new Error('PSL ICANN and PRIVATE sections are both required');
  const ordered = [...rules].sort();
  if (ordered.length < minRules) throw new Error(`PSL rule count is too small: ${ordered.length}`);
  for (const required of ['com', 'co.uk', 'github.io', '*.ck', '!www.ck']) {
    if (!rules.has(required)) throw new Error(`PSL sanity check failed: missing ${required}`);
  }
  return { version, commit, rules: ordered };
}

export function renderModule({ version, commit, rules }, { minRules = 9000 } = {}) {
  if (!Array.isArray(rules) || rules.length < minRules) throw new Error('Refusing to render an incomplete PSL');
  const body = rules.join('\n');
  // PSL labels cannot contain template-literal syntax, but assert that invariant
  // so a future upstream formatting change cannot turn data into TypeScript code.
  if (body.includes('`') || body.includes('${')) throw new Error('Unexpected template-literal token in PSL data');
  return `/** Generated by scripts/update-public-suffix-list.mjs from the official Public Suffix List.\n * Upstream VERSION: ${version}\n * Upstream COMMIT: ${commit}\n * Data license: Mozilla Public License 2.0 (MPL-2.0).\n */\nexport const PUBLIC_SUFFIX_LIST_VERSION = '${version}';\nexport const PUBLIC_SUFFIX_LIST_COMMIT = '${commit}';\nexport const PUBLIC_SUFFIX_RULE_COUNT = ${rules.length};\nexport const PUBLIC_SUFFIX_RULES = String.raw\`${body}\`;\n\nconst exactRules = new Set<string>();\nconst wildcardRules = new Set<string>();\nconst exceptionRules = new Set<string>();\nfor (const rawRule of PUBLIC_SUFFIX_RULES.split('\\n')) {\n  const rule = rawRule.trim();\n  if (!rule) continue;\n  if (rule.startsWith('!')) exceptionRules.add(rule.slice(1));\n  else if (rule.startsWith('*.')) wildcardRules.add(rule.slice(2));\n  else exactRules.add(rule);\n}\n\n/** Return true only when hostname itself is a public suffix under PSL rules. */\nexport function isPublicSuffix(hostname: string): boolean {\n  const value = String(hostname || '').toLowerCase().replace(/\\.$/, '');\n  const labels = value.split('.');\n  if (!value || labels.some((label) => !label)) return true;\n\n  let matchedLength = 1; // PSL's implicit '*' rule.\n  for (let start = 0; start < labels.length; start += 1) {\n    const suffix = labels.slice(start).join('.');\n    if (exceptionRules.has(suffix)) return false;\n    matchedLength = Math.max(matchedLength, exactRules.has(suffix) ? labels.length - start : 0);\n    if (start + 1 < labels.length && wildcardRules.has(labels.slice(start + 1).join('.'))) {\n      matchedLength = Math.max(matchedLength, labels.length - start);\n    }\n  }\n  return labels.length === matchedLength;\n}\n`;
}

export function renderNotice({ version, commit }) {
  return `# Public Suffix List data notice\n\nMad Station bundles the Public Suffix List (PSL), including ICANN and PRIVATE rules, in \`src/main/public-suffix-list.ts\`. It is used for authentication-domain allowlist normalization, not as a general URL trust policy.\n\n- Upstream project: [Public Suffix List](https://publicsuffix.org/list/)\n- Authoritative source: <${OFFICIAL_PSL_URL}>\n- Bundled upstream version: \`${version}\`\n- Upstream commit: \`${commit}\`\n- Data license: Mozilla Public License 2.0; see \`MPL-2.0.txt\`.\n- Refresh command: \`npm run update:psl\` (uses only the official URL and rejects redirects).\n\nThe PSL is maintained over time. Refresh the data before security-sensitive releases and rerun the auth-domain/PSL regression suite.\n`;
}

export function renderThirdPartyNotice({ version, commit }) {
  return `# Third-party notices\n\n## Public Suffix List\n\nMad Station includes Public Suffix List data with ICANN and PRIVATE rules. It is distributed under the Mozilla Public License 2.0 (MPL-2.0); the license text is provided in \`docs/licenses/MPL-2.0.txt\`.\n\nUpstream: ${OFFICIAL_PSL_URL}\nBundled upstream version: ${version}\nUpstream commit: ${commit}\nRefresh with \`npm run update:psl\`.\n`;
}

export async function fetchOfficialPsl(fetchImpl = fetch) {
  const response = await fetchImpl(OFFICIAL_PSL_URL, {
    redirect: 'error',
    signal: AbortSignal.timeout(20_000),
    headers: { 'user-agent': 'MadStation-PSL-Updater/1.0' },
  });
  if (!response.ok || new URL(response.url).hostname !== 'publicsuffix.org') {
    throw new Error(`Official PSL request failed (${response.status})`);
  }
  return response.text();
}

async function main() {
  const source = await fetchOfficialPsl();
  const data = parseOfficialPsl(source);
  await writeFile(path.join(ROOT, 'src/main/public-suffix-list.ts'), renderModule(data));
  await writeFile(path.join(ROOT, 'docs/licenses/Public-Suffix-List-Notice.md'), renderNotice(data));
  await writeFile(path.join(ROOT, 'docs/licenses/THIRD_PARTY_NOTICES.md'), renderThirdPartyNotice(data));
  process.stdout.write(`Updated PSL ${data.version} (${data.commit}), ${data.rules.length} rules.\n`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((error) => {
    process.stderr.write(`PSL update failed: ${error instanceof Error ? error.message : String(error)}\n`);
    process.exitCode = 1;
  });
}
