/** Public, renderer-safe contracts shared by the preload bridge and UI. */
export type JsonRecord = Record<string, unknown>;
export type ApiResult = { ok: boolean; error?: string; [key: string]: unknown };
export type WorkspaceApp = 'launcher' | 'ai-hub' | 'clipboard' | 'ai-lab' | 'instruction-forge' | 'video-hub' | 'image-hub';
export type ControlMode = 'launcher' | 'app';
export type ToolbarNavigationAction = 'back' | 'forward' | 'reload' | 'stop';

export interface ToolbarState {
  sidebarHidden: boolean;
  theme: string;
  accent: string;
  surfaceStyle: string;
  backgroundStyle: string;
  cornerStyle: string;
  buttonCorner: string;
  buttonBackground: string;
  borderStyle: string;
  shadowStyle: string;
  cardSpacing: string;
  borderSpacing: string;
  animateHover: boolean;
  reduceMotion: boolean;
  showStatusBar: boolean;
  remoteIcons: boolean;
  hasAccount: boolean;
  accountName: string;
  accountIcon: string;
  url: string;
  title: string;
  loading: boolean;
  canGoBack: boolean;
  canGoForward: boolean;
}

export interface ToolbarApi {
  getState(): Promise<ToolbarState | { error: string }>;
  navigate(action: ToolbarNavigationAction): Promise<ApiResult>;
  openExternal(): Promise<ApiResult>;
  windowMinimize(): Promise<ApiResult>;
  windowToggleMaximize(): Promise<ApiResult>;
  windowClose(): Promise<ApiResult>;
  toggleSidebar(): Promise<ApiResult>;
  showSidebar(): Promise<ApiResult>;
  onState(callback: (data: ToolbarState) => void): () => void;
  onSidebarState(callback: (data: { hidden: boolean }) => void): () => void;
}

